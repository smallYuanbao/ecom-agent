"""证据闸：判断召回结果是否足以支撑回答。

**只用一个信号：top1 的余弦相似度。** 阈值由实测数据定，见下面的推导。

## 阈值怎么来的

在 45 条评测查询 + 10 条域外探测上测 top1 相似度：

| 类型 | 范围 |
|---|---|
| 可答题（n=42） | **0.566 – 0.803**，中位数 0.670 |
| 该拒答（n=3） | 0.423 – 0.500 |
| 域外探测（n=8） | 0.323 – **0.572** |

可答题最低 0.566 与拒答题最高 0.500 之间有干净的间隔，取中间偏上 **0.55**。

### 阈值扫描（同一批分数，只改门槛）

| 阈值 | 可答题放行 | 拒答+域外拦住 |
|---|---|---|
| 0.45 | 42/42 | **6/11** |
| 0.50 | 42/42 | 9/11 |
| 0.53 | 42/42 | 10/11 |
| **0.55** | **42/42** | **10/11** |
| 0.58 | 41/42 | **11/11** |
| 0.62 | 35/42 | 11/11 |

**0.58 严格更"安全"**：拦住全部负样本，代价是把「FB-30 保修多久」（0.566）也拒了。

选 0.55 的理由：那条被拒的是**合法且常见的型号类问题**，而漏掉的那条
（能分期付款吗）在生成阶段还有一道防线——prompt 要求"只依据检索作答"，
证据里没有分期信息时模型应当拒答，而不是编。**这道防线是否真有效，
由 Task 10 的质量传导表验证**（看"闸放行但答案缺要点/编造"的比例）。

若 Task 10 显示编造确实发生，就升到 0.58 或加第二信号。

## 这个闸的已知漏洞（重要）

**「能分期付款吗」的 top1 相似度是 0.572——比合法的「FB-30 保修多久」（0.566）还高。**

也就是说：**没有任何单一阈值能同时做到"放行所有可答题"和"拦住所有域外问题"**。
原因是相似度衡量的是"话题是否相近"，而不是"这段话有没有回答这个问题"。

选 0.55 是权衡：宁可偶尔放过一条（如分期付款），也不要把大量合法问题拒掉。
被拒的会落池，走飞轮补语料。

**升级触发条件**（满足任一就换方案）：

| 触发 | 说明 |
|---|---|
| 兜底率 > 10% | 拒得太多，说明阈值或语料有问题 |
| 出现"明显答非所问但通过了闸" | 需要加第二信号 |

**两个候选方案**（都留到触发后再做）：

1. **证据自评**：把 top-k 原文给模型，问"这些证据够不够回答"——参考实现的做法，
   多一次 LLM 调用，能判断"有没有答案"而不只是"话题近不近"
2. **关键词锚点**：查询与 chunk 至少共享一个实词。**但它会误杀口语问法**
   （「买回来不想要了还能退吗」和「退货」没有共同词），所以不能单独用
"""
from app.config import get_settings


def is_strong(hits: list[dict]) -> bool:
    """证据是否足够。空列表直接 False（fail-closed）。

    **比较的是 `similarity`，不是 `distance`，也不是 `rrf_score`**：

    - `distance` 是余弦距离（越小越像），方向相反
    - `rrf_score` 量纲是 `1/(60+rank)`，最大约 0.033，永远达不到阈值
    """
    if not hits:
        return False
    threshold = get_settings().evidence_threshold
    return hits[0]["similarity"] >= threshold


def explain(hits: list[dict]) -> dict:
    """闸的判定依据，用于落池与排查。

    把 top1 的信息记下来，是因为"为什么被拒"必须可解释——
    只有分数没有 id 的话，无法判断是阈值问题还是语料缺口。
    """
    threshold = get_settings().evidence_threshold
    if not hits:
        return {"passed": False, "reason": "zero_hits", "threshold": threshold}

    top = hits[0]
    return {
        "passed": top["similarity"] >= threshold,
        "reason": "below_threshold" if top["similarity"] < threshold else "passed",
        "threshold": threshold,
        "top1_id": top["id"],
        "top1_similarity": round(top["similarity"], 4),
    }
